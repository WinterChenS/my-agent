#!/usr/bin/env bash
# Task 10.1 / 10.2 / 10.3 的 API 级验收（可复跑）。
#
# 覆盖：上传 → 存储路由（文本类入 DB / 二进制进 MinIO）→ 去重 → 物化到 Agent 工作区
#       → 列表 → 下载（DB 直返 / MinIO 直链，比对 sha256）
#       → Agent 能读到上传文件（D20）→ 产物自动登记（D22，含排除框架内部目录）。
#
# 踩过的坑（都写在这里避免复发）：
#   1. curl 是 Windows 原生程序，读不了 Git Bash 的 /tmp/... 路径 → 临时文件用仓库内相对路径。
#   2. 工具参数里不要放中文：bash 传 env 给 Windows Python 会按 ANSI 代码页解码，中文变乱码，
#      工具调用直接 ERROR。测试数据统一 ASCII。
#   3. 不要在同一端口反复重启桩：后端连接池会留下死连接，后续 run 直接 IOException 失败，
#      根本到不了桩。这里改成两个桩进程、两个端口，全程不重启。
set -uo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
JAVA_BIN="/c/Program Files/Java/jdk-21.0.3+9/bin/java"
MVN="/c/tools/apache-maven-3.9.16/bin/mvn"
PG_JAR="C:\\Users\\Administrator\\.m2\\repository\\org\\postgresql\\postgresql\\42.7.11\\postgresql-42.7.11.jar"
API="http://localhost:8080"
STUB_A_PORT=8099   # read_file 桩
STUB_B_PORT=8098   # write_file 桩
export JAVA_HOME="${JAVA_HOME:-C:\\Program Files\\Java\\jdk-21.0.3+9}"
export PATH="/d/Program Files/nodejs:/c/tools/apache-maven-3.9.16/bin:$PATH"

cd "$ROOT"
RUN_ID=$(date +%s)
WORK=".p10tmp-$RUN_ID"
OUT_NAME="agent-out-$RUN_ID.md"
PIDS=()
cleanup() {
  for pid in "${PIDS[@]:-}"; do kill "$pid" 2>/dev/null || true; done
  rm -rf "$WORK"
  sleep 1
}
trap cleanup EXIT
mkdir -p "$WORK"

free_port() {
  local pids
  pids=$(netstat -ano 2>/dev/null | grep LISTENING | grep ":$1 " | awk '{print $5}' | sort -u)
  for pid in $pids; do [ -n "$pid" ] && taskkill //PID "$pid" //F >/dev/null 2>&1 || true; done
}
wait_for() { for _ in $(seq 1 "${2:-60}"); do [ -n "$(curl -s -m 2 "$1" || true)" ] && return 0; sleep 2; done; echo "等待超时: $1" >&2; return 1; }
id_of() { sed -n 's/.*"id":\([0-9]*\).*/\1/p' | head -1; }

echo "== 0/8 清理端口 =="
free_port 8080; free_port "$STUB_A_PORT"; free_port "$STUB_B_PORT"; sleep 2

echo "== 1/8 启动两个桩（读/写各一）+ 打包并启动后端 =="
STUB_REPLY_FROM_MODEL=1 STUB_TOOL_NAME="read_file" \
  STUB_TOOL_ARGS='{"path":"uploads/note.md"}' PORT="$STUB_A_PORT" \
  nohup python "$ROOT/tools/llm-stub/stub.py" >/tmp/p10-stub-read.log 2>&1 &
PIDS+=($!)
STUB_REPLY_FROM_MODEL=1 STUB_TOOL_NAME="write_file" \
  STUB_TOOL_ARGS="{\"path\":\"$OUT_NAME\",\"content\":\"# generated by agent (ascii only)\"}" PORT="$STUB_B_PORT" \
  nohup python "$ROOT/tools/llm-stub/stub.py" >/tmp/p10-stub-write.log 2>&1 &
PIDS+=($!)
wait_for "http://localhost:$STUB_A_PORT/health" 15
wait_for "http://localhost:$STUB_B_PORT/health" 15
[ -n "$(curl -s -m 2 "http://localhost:$STUB_B_PORT/health" || true)" ] || echo "   警告：写桩未就绪"
(cd "$ROOT/backend/agent-server" && "$MVN" -B -q package -DskipTests) || { echo "构建失败" >&2; exit 1; }
nohup "$JAVA_BIN" -jar "$ROOT/backend/agent-server/target/agent-server-0.0.1-SNAPSHOT.jar" >/tmp/p10-app.log 2>&1 &
PIDS+=($!)
wait_for "$API/api/health" 90
grep -o "MinIO bucket 已存在[^ ]*\|已创建 MinIO bucket[^ ]*" /tmp/p10-app.log | head -1

TOKEN=$(curl -s -X POST "$API/api/auth/login" -H 'Content-Type: application/json' \
  -d '{"username":"admin","password":"Admin@123"}' | sed -n 's/.*"token":"\([^"]*\)".*/\1/p')
AUTH="Authorization: Bearer $TOKEN"
CT="Content-Type: application/json"
post() { curl -s -X POST "$API$1" -H "$AUTH" -H "$CT" --data-binary @-; }

echo "== 2/8 准备 provider/model/agent/会话（读、写各一套）=="
PID_A=$(printf '{"name":"P10-Read-%s","providerType":"OPENAI_COMPATIBLE","baseUrl":"http://localhost:%s/v1","apiKey":"k","status":"ENABLED"}' "$RUN_ID" "$STUB_A_PORT" | post /api/model-providers | id_of)
MID_A=$(printf '{"providerId":%s,"modelId":"p10-read-%s"}' "$PID_A" "$RUN_ID" | post /api/models | id_of)
PID_B=$(printf '{"name":"P10-Write-%s","providerType":"OPENAI_COMPATIBLE","baseUrl":"http://localhost:%s/v1","apiKey":"k","status":"ENABLED"}' "$RUN_ID" "$STUB_B_PORT" | post /api/model-providers | id_of)
MID_B=$(printf '{"providerId":%s,"modelId":"p10-write-%s"}' "$PID_B" "$RUN_ID" | post /api/models | id_of)
AGENT_A="p10-read-$RUN_ID"; AGENT_B="p10-write-$RUN_ID"
printf '{"name":"%s","agentId":"%s","sysPrompt":"You are a helper.","modelId":%s,"permissionMode":"ALWAYS_ALLOW","maxIterations":4,"status":"ENABLED","skillIds":[],"mcpServerIds":[]}' "$AGENT_A" "$AGENT_A" "$MID_A" | post /api/agents >/dev/null
printf '{"name":"%s","agentId":"%s","sysPrompt":"You are a helper.","modelId":%s,"permissionMode":"ALWAYS_ALLOW","maxIterations":4,"status":"ENABLED","skillIds":[],"mcpServerIds":[]}' "$AGENT_B" "$AGENT_B" "$MID_B" | post /api/agents >/dev/null
agent_id_of() {
  curl -s "$API/api/agents?current=1&size=300" -H "$AUTH" | AG="$1" python -c "
import os,sys,json
for a in json.load(sys.stdin)['data']['records']:
    if a['agentId']==os.environ['AG']: print(a['id']); break"
}
AID_A=$(agent_id_of "$AGENT_A"); AID_B=$(agent_id_of "$AGENT_B")
SID=$(printf '{"agentId":%s,"title":"p10 upload"}' "$AID_A" | post /api/sessions | id_of)
SID2=$(printf '{"agentId":%s,"title":"p10 artifacts"}' "$AID_B" | post /api/sessions | id_of)
thread_of() {
  curl -s "$API/api/sessions" -H "$AUTH" | S="$1" python -c "
import os,sys,json
for s in json.load(sys.stdin)['data']:
    if s['id']==int(os.environ['S']): print(s['threadId']); break"
}
THREAD=$(thread_of "$SID"); THREAD2=$(thread_of "$SID2")
[ -n "$MID_A" ] && [ -n "$MID_B" ] && [ -n "$AID_A" ] && [ -n "$AID_B" ] && [ -n "$THREAD" ] && [ -n "$THREAD2" ] \
  || { echo "fixture 失败: MID_A=$MID_A MID_B=$MID_B AID_A=$AID_A AID_B=$AID_B THREAD=$THREAD THREAD2=$THREAD2" >&2; exit 1; }
echo "   session=$SID(读) session2=$SID2(写) agent=$AGENT_A/$AGENT_B"

echo "== 3/8 上传文本类（.md）=="
printf '# requirements\nuploaded doc\n' > "$WORK/note.md"
MD=$(curl -s -w "\nHTTP=%{http_code}" -X POST "$API/api/artifacts/upload" -H "$AUTH" -F "sessionId=$SID" -F "file=@$WORK/note.md;type=text/markdown")
echo "   $(echo "$MD" | tail -1)"
MD=$(echo "$MD" | sed '$d')

echo "== 4/8 上传二进制（.png）=="
printf '\x89PNG\r\n\x1a\nFAKEPNGDATA' > "$WORK/pic.png"
PNG=$(curl -s -w "\nHTTP=%{http_code}" -X POST "$API/api/artifacts/upload" -H "$AUTH" -F "sessionId=$SID" -F "file=@$WORK/pic.png;type=image/png")
echo "   $(echo "$PNG" | tail -1)"
PNG=$(echo "$PNG" | sed '$d')

echo "== 5/8 重复上传同一内容（应去重）=="
MD2=$(curl -s -X POST "$API/api/artifacts/upload" -H "$AUTH" -F "sessionId=$SID" -F "file=@$WORK/note.md;type=text/markdown")
echo "   md id 一致? $([ "$(echo "$MD" | id_of)" = "$(echo "$MD2" | id_of)" ] && echo yes || echo no)"

echo "== 6/8 列表 =="
curl -s "$API/api/artifacts?sessionId=$SID" -H "$AUTH" | python -c "
import sys,json
for r in json.load(sys.stdin)['data']:
    print(f\"   id={r['id']} role={r['role']} storage={r['storage']} file={r['fileName']} size={r['sizeBytes']} status={r['status']}\")
"

echo "== 7/8 下载（DB 直返 / MINIO 直链，比对 sha256）=="
MDID=$(echo "$MD" | id_of); PNGID=$(echo "$PNG" | id_of)
echo -n "   DB 下载: "; curl -s "$API/api/artifacts/$MDID/download" -H "$AUTH" | tr -d '\n'; echo
echo -n "   MINIO 下载 HTTP: "; curl -s -o "$WORK/dl.png" -w "%{http_code}\n" -L "$API/api/artifacts/$PNGID/download" -H "$AUTH"
echo "   sha256 一致? $([ "$(sha256sum "$WORK/dl.png" | cut -c1-16)" = "$(sha256sum "$WORK/pic.png" | cut -c1-16)" ] && echo yes || echo no)"

echo "== 8/8 物化 + Agent 读取（D20）+ 产物自动登记（D22）=="
echo -n "   工作区 uploads/: "; ls "$ROOT/.myagent-workspace/1/uploads" 2>/dev/null | tr '\n' ' '; echo
echo "   8a) Agent 读上传的文件…"
printf '{"threadId":"%s","runId":"p10r-%s","messages":[{"id":"m1","role":"user","content":"read uploads/note.md"}],"forwardedProps":{"agentId":"%s"}}' \
  "$THREAD" "$RUN_ID" "$AGENT_A" | curl -sN -X POST "$API/agui/run" -H "$AUTH" -H "$CT" --data-binary @- --max-time 120 > "$WORK/read.sse"
if grep -q "uploaded doc" "$WORK/read.sse"; then echo "   Agent 读到上传内容? yes"; else echo "   Agent 读到上传内容? NO"; fi
grep -o '"type":"TOOL_CALL_RESULT".\{0,150\}' "$WORK/read.sse" | head -1

echo "   8b) Agent 写文件（触发产物登记）…"
printf '{"threadId":"%s","runId":"p10w-%s","messages":[{"id":"m1","role":"user","content":"write the summary file please"}],"forwardedProps":{"agentId":"%s"}}' \
  "$THREAD2" "$RUN_ID" "$AGENT_B" | curl -sN -X POST "$API/agui/run" -H "$AUTH" -H "$CT" --data-binary @- --max-time 120 > "$WORK/write.sse"
grep -o '"type":"TOOL_CALL_RESULT".\{0,150\}' "$WORK/write.sse" | head -1
echo "   后端“已登记”日志: $(grep -c '已登记' /tmp/p10-app.log) 条"
curl -s "$API/api/artifacts?sessionId=$SID2" -H "$AUTH" | OUT="$OUT_NAME" python -c "
import os,sys,json
rows=json.load(sys.stdin)['data']
art=[r for r in rows if r['role']=='ARTIFACT']
print('   ARTIFACT 数量:', len(art))
for r in art: print(f\"     {r['fileName']} ({r['storage']})\")
print('   期望文件', os.environ['OUT'], '出现?', any(r['fileName']==os.environ['OUT'] for r in art))
bad=[r for r in rows if any(x in (r['fileName'] or '') for x in ('memory','sessions','.skills-cache','events','default'))]
print('   框架内部文件混入?', 'YES' if bad else 'no')
"
echo "   产物表内 SQL 抽查:"
mkdir -p /tmp/dbprobe && cd /tmp/dbprobe
cat > P10.java <<EOF
import java.sql.*;
public class P10 {
  public static void main(String[] a) throws Exception {
    try (Connection c=DriverManager.getConnection("jdbc:postgresql://localhost:5432/agent_platform","app_user","CHANGE_ME");
         Statement s=c.createStatement()) {
      ResultSet rs=s.executeQuery("select role, storage, count(*) from artifact where session_id=$SID2 group by 1,2 order by 1,2");
      while(rs.next()) System.out.println("     role="+rs.getString(1)+" storage="+rs.getString(2)+" count="+rs.getInt(3));
    }
  }
}
EOF
"${JAVA_BIN%/java}/java" -cp "$PG_JAR" P10.java 2>&1 | head -6
echo
echo "P10 API 级验收完成"
